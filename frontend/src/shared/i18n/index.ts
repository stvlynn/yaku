export function readingControlsLabel(editing: boolean) {
  return editing
    ? `${copy.moreReadingControls} · ${copy.temporaryEditingOn}`
    : copy.moreReadingControls;
}

export function subtitleTrackLabel(index: number) {
  return `Track ${index}`;
}

export function temporaryTranslationUntil(time: string) {
  return `Auto-translate until ${time}`;
}
export function temporaryTranslationDuration(minutes: number) {
  return minutes === 0 ? copy.temporaryDisabled : `${minutes} minutes`;
}

export function imageBatchProgress(
  completed: number,
  queued: number,
  skipped = 0,
) {
  return `${completed.toLocaleString()} translated · ${queued.toLocaleString()} queued${skipped ? ` · ${skipped.toLocaleString()} without text` : ""}`;
}
export function imageBatchFailures(count: number) {
  return `${count.toLocaleString()} image${count === 1 ? "" : "s"} could not be translated.`;
}

export function characterCount(count: number) {
  return `${count.toLocaleString()} ${copy.characters}`;
}
export function percentage(value: number) {
  return `${Math.round(value)}%`;
}
export function cacheDescription(files: number | undefined, bytes: number) {
  const size = `${(bytes / 1024 / 1024).toFixed(1)} ${copy.bytesUnit}`;
  return files === undefined
    ? size
    : `${files.toLocaleString()} ${copy.files} · ${size}`;
}
export function progressDescription(completed: number, total: number) {
  return `${completed.toLocaleString()} / ${total.toLocaleString()} ${copy.completed}`;
}
export function pdfReadingPageLabel(page: number) {
  return `${copy.resultText} · ${copy.page} ${page}`;
}
